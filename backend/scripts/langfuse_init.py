"""Generate Langfuse secrets + project API keys, and wire the SDK keys into the app .env.

    python scripts/langfuse_init.py            (or: make langfuse-init)

Writes (both gitignored, mode 600):
  infra/langfuse/.env   server secrets + first-boot admin login + project API keys
  .env                  LANGFUSE_PUBLIC_KEY / LANGFUSE_SECRET_KEY / LANGFUSE_BASE_URL / SG_TRACING_ENABLED

Refuses to overwrite an existing infra/langfuse/.env: the database volumes are initialised with
these passwords, so silently rotating them would lock Langfuse out of its own data.
Never prints a secret; it only says which file holds them.
"""

import argparse
import re
import secrets
import sys
import uuid
from pathlib import Path

REPO_ROOT = Path(__file__).resolve().parents[2]
ADMIN_EMAIL = "admin@supportgraph.local"
DEFAULT_WEB_PORT = 3100


def generate_server_env(web_port: int = DEFAULT_WEB_PORT) -> dict[str, str]:
    return {
        "LANGFUSE_WEB_PORT": str(web_port),
        "LANGFUSE_PG_PASSWORD": secrets.token_hex(16),
        "CLICKHOUSE_PASSWORD": secrets.token_hex(16),
        "MINIO_ROOT_PASSWORD": secrets.token_hex(16),
        "REDIS_AUTH": secrets.token_hex(16),
        "NEXTAUTH_SECRET": secrets.token_hex(32),
        "SALT": secrets.token_hex(32),
        "ENCRYPTION_KEY": secrets.token_hex(32),  # must be exactly 64 hex chars
        "LANGFUSE_INIT_PROJECT_PUBLIC_KEY": f"pk-lf-{uuid.uuid4()}",
        "LANGFUSE_INIT_PROJECT_SECRET_KEY": f"sk-lf-{uuid.uuid4()}",
        "LANGFUSE_INIT_USER_EMAIL": ADMIN_EMAIL,
        "LANGFUSE_INIT_USER_PASSWORD": secrets.token_urlsafe(12),
    }


def _write_private(path: Path, text: str) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(text)
    path.chmod(0o600)


def upsert_env(path: Path, updates: dict[str, str]) -> None:
    """Set KEY=value lines in a dotenv file, replacing existing keys and keeping everything else."""
    lines = path.read_text().splitlines() if path.exists() else []
    remaining = dict(updates)
    for i, line in enumerate(lines):
        m = re.match(r"\s*([A-Za-z_][A-Za-z0-9_]*)\s*=", line)
        if m and m.group(1) in remaining:
            lines[i] = f"{m.group(1)}={remaining.pop(m.group(1))}"
    lines.extend(f"{k}={v}" for k, v in remaining.items())
    _write_private(path, "\n".join(lines) + "\n")


def init(repo_root: Path = REPO_ROOT, web_port: int = DEFAULT_WEB_PORT, force: bool = False) -> int:
    server_env_path = repo_root / "infra" / "langfuse" / ".env"
    if server_env_path.exists() and not force:
        print(f"{server_env_path.relative_to(repo_root)} already exists; leaving it untouched.\n"
              "Rotating secrets under existing volumes breaks Langfuse. To start over, run:\n"
              "  make langfuse-reset   (deletes ALL Langfuse data) then  make langfuse-init")
        return 1

    env = generate_server_env(web_port)
    _write_private(server_env_path, "# Generated by scripts/langfuse_init.py. Secret. Never commit.\n"
                   + "".join(f"{k}={v}\n" for k, v in env.items()))

    app_env = repo_root / ".env"
    if not app_env.exists():
        example = repo_root / ".env.example"
        app_env.write_text(example.read_text() if example.exists() else "")
    upsert_env(app_env, {
        "LANGFUSE_PUBLIC_KEY": env["LANGFUSE_INIT_PROJECT_PUBLIC_KEY"],
        "LANGFUSE_SECRET_KEY": env["LANGFUSE_INIT_PROJECT_SECRET_KEY"],
        "LANGFUSE_BASE_URL": f"http://localhost:{web_port}",
        "SG_TRACING_ENABLED": "true",
    })

    print("Langfuse secrets generated (not printed).")
    print(f"  server secrets + admin login : {server_env_path.relative_to(repo_root)}")
    print(f"  SDK keys + tracing flag      : {app_env.relative_to(repo_root)}")
    print(f"  UI will be at                : http://localhost:{web_port}")
    print(f"  admin email                  : {ADMIN_EMAIL}  (password: LANGFUSE_INIT_USER_PASSWORD in the server .env)")
    print("Next: make langfuse-up")
    return 0


if __name__ == "__main__":
    ap = argparse.ArgumentParser()
    ap.add_argument("--web-port", type=int, default=DEFAULT_WEB_PORT)
    ap.add_argument("--force", action="store_true", help="overwrite existing secrets (only after make langfuse-reset)")
    a = ap.parse_args()
    sys.exit(init(web_port=a.web_port, force=a.force))
